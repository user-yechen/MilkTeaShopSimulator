using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using UnityEditor;
using UnityEngine;

/// <summary>
/// 文案表导入：校验 CSV、生成 GTextKeys 常量。
/// 菜单：奶茶店/文案/校验并生成 Key
/// 命令行：-executeMethod TextImportTool.ImportForCI（失败退出码 1）
/// </summary>
public static class TextImportTool
{
    public const string CsvPath = "Assets/Resources/文案/文案表.csv";
    public const string KeysPath = "Assets/脚本/文案/GTextKeys.cs";

    static readonly string[] Required = { "key", "category", "zh" };
    static readonly Regex KeyPattern = new Regex(@"^[a-z0-9_]+(\.[a-z0-9_]+)+$");

    [MenuItem("奶茶店/文案/校验并生成 Key", false, 210)]
    public static void ValidateAndGenerate()
    {
        bool ok = Run();
        if (ok) Debug.Log("[文案] 校验通过，GTextKeys.cs 已更新");
        else Debug.LogError("[文案] 校验失败，见上方日志");
    }

    [MenuItem("奶茶店/文案/打开文案表", false, 211)]
    public static void OpenCsv()
    {
        var asset = AssetDatabase.LoadAssetAtPath<TextAsset>(CsvPath);
        if (asset != null) AssetDatabase.OpenAsset(asset);
        else Debug.LogError("[文案] 找不到 " + CsvPath);
    }

    /// <summary>命令行入口</summary>
    public static void ImportForCI()
    {
        bool ok = Run();
        EditorApplication.Exit(ok ? 0 : 1);
    }

    /// <summary>运行时加载自检：确认 Resources 路径、CSV 解析、Key 常量都对得上</summary>
    public static void SmokeTest()
    {
        GText.Reload();
        int count = GText.Count;
        string sample = GText.Get(GTextKeys.UiShopTitle, "<missing>");
        string formatted = GText.Format(GTextKeys.UiDayEndBody, 120, 360);
        Debug.Log("[文案] 自检：key 数=" + count + "，示例=" + sample + "，格式化=" + formatted.Replace("\n", " / "));
        EditorApplication.Exit(count > 0 && sample != "<missing>" ? 0 : 1);
    }

    static bool Run()
    {
        if (!File.Exists(CsvPath))
        {
            Debug.LogError("[文案] 找不到 " + CsvPath);
            return false;
        }

        string csv = File.ReadAllText(CsvPath, Encoding.UTF8);
        List<string[]> rows = GText.ParseRows(csv);
        if (rows.Count < 2)
        {
            Debug.LogError("[文案] 文案表为空");
            return false;
        }

        string[] header = rows[0].Select(h => h.Trim()).ToArray();
        var index = new Dictionary<string, int>();
        for (int i = 0; i < header.Length; i++) index[header[i]] = i;

        foreach (string col in Required)
        {
            if (!index.ContainsKey(col))
            {
                Debug.LogError("[文案] 缺少必需列：" + col);
                return false;
            }
        }

        int keyCol = index["key"];
        int catCol = index["category"];
        int zhCol = index["zh"];
        int maxCol = index.ContainsKey("maxChars") ? index["maxChars"] : -1;

        var errors = new List<string>();
        var keys = new List<string>();
        var seen = new HashSet<string>();
        var constNames = new Dictionary<string, string>();

        for (int r = 1; r < rows.Count; r++)
        {
            string[] row = rows[r];
            string where = "第 " + (r + 1) + " 行";

            string key = Cell(row, keyCol).Trim();
            string cat = Cell(row, catCol).Trim();
            string zh = Cell(row, zhCol);

            if (string.IsNullOrEmpty(key)) { errors.Add(where + "：key 为空"); continue; }
            if (!KeyPattern.IsMatch(key)) errors.Add(where + "：key 格式非法（" + key + "）");
            if (!seen.Add(key)) errors.Add(where + "：key 重复（" + key + "）");
            if (string.IsNullOrEmpty(cat)) errors.Add(where + "：" + key + " 的 category 为空");
            if (string.IsNullOrEmpty(zh)) errors.Add(where + "：" + key + " 的 zh 为空");

            if (maxCol >= 0 && !string.IsNullOrEmpty(zh))
            {
                int max;
                if (int.TryParse(Cell(row, maxCol), out max) && max > 0 && zh.Length > max)
                    errors.Add(where + "：" + key + " 中文 " + zh.Length + " 字，超过上限 " + max);
            }

            string constName = ToConstName(key);
            string existingKey;
            if (constNames.TryGetValue(constName, out existingKey))
                errors.Add(where + "：常量名冲突 " + constName + "（" + existingKey + " / " + key + "）");
            else
                constNames[constName] = key;

            keys.Add(key);
        }

        if (errors.Count > 0)
        {
            foreach (string e in errors) Debug.LogError("[文案] " + e);
            Debug.LogError("[文案] 共 " + errors.Count + " 处错误");
            return false;
        }

        WriteKeys(keys);
        return true;
    }

    static void WriteKeys(List<string> keys)
    {
        keys.Sort(StringComparer.Ordinal);
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine("// 由 TextImportTool 从 文案表.csv 生成，不要手改。");
        sb.AppendLine("// 重新生成：菜单 奶茶店/文案/校验并生成 Key");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine();
        sb.AppendLine("public static class GTextKeys");
        sb.AppendLine("{");
        foreach (string key in keys)
            sb.AppendLine("    public const string " + ToConstName(key) + " = \"" + key + "\";");
        sb.AppendLine("}");

        string content = sb.ToString();
        string old = File.Exists(KeysPath) ? File.ReadAllText(KeysPath, Encoding.UTF8) : null;
        if (old != content)
        {
            Directory.CreateDirectory(Path.GetDirectoryName(KeysPath));
            File.WriteAllText(KeysPath, content, new UTF8Encoding(false));
            AssetDatabase.ImportAsset(KeysPath);
            Debug.Log("[文案] 已写入 " + KeysPath + "（" + keys.Count + " 个 key）");
        }
    }

    static string Cell(string[] row, int col)
    {
        return col >= 0 && col < row.Length ? row[col] : string.Empty;
    }

    static string ToConstName(string key)
    {
        var parts = key.Split(new[] { '.', '_' }, StringSplitOptions.RemoveEmptyEntries);
        var sb = new StringBuilder();
        foreach (string p in parts)
        {
            sb.Append(char.ToUpperInvariant(p[0]));
            if (p.Length > 1) sb.Append(p.Substring(1));
        }
        return sb.ToString();
    }
}
